#!/usr/bin/env python3
# Copyright 2026 Timothy Place and the catenae contributors
"""The amalgamation (D26, PLAN.md section 7.4): catenae for any other build system.

    scripts/amalgamate.py --out DIR

writes DIR/catenae.cpp, the whole compiled core as one source (every file of src/ in name
order, a private header of src/ inlined at its first include), and DIR/include/, a copy of the
public headers. A consumer compiles catenae.cpp with DIR/include on its include path and its
own target flags. Once C0b adds the build-written catenae/config.h, a default one is written
beside the headers here.

An assumption of use, stated in the file: no compiler honours a contraction pragma reliably,
so the amalgamation cannot carry the library's contraction policy, and catenae.cpp must be
compiled with contraction off (-ffp-contract=off; MSVC's default /fp:precise).
"""
import argparse
import pathlib
import re
import shutil
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')
BANNER = """// catenae.cpp: catenae's compiled core in one file, generated by scripts/amalgamate.py.
// Copyright 2026 Timothy Place and the catenae contributors
//
// Compile it with the include/ directory beside it on the include path, with your target's
// flags, and with floating-point contraction off (-ffp-contract=off; MSVC's default
// /fp:precise): the library's bit pins assume it, and no pragma can carry it reliably
// (PLAN.md section 7.4). Do not edit: regenerate it.
"""


def expand(path: pathlib.Path, seen: set[pathlib.Path]) -> list[str]:
    out = []
    for line in path.read_text().splitlines():
        m = INCLUDE.match(line)
        private = (REPO / "src" / m.group(1)).resolve() if m else None
        if private is not None and private.is_file():
            if private not in seen:
                seen.add(private)
                out.append(f"// ---- src/{m.group(1)} (inlined) ----")
                out += expand(private, seen)
            continue
        out.append(line)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True, type=pathlib.Path)
    args = ap.parse_args()
    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    sources = sorted((REPO / "src").glob("*.cpp"))
    if not sources:
        raise SystemExit("no sources under src/")
    lines, seen = [BANNER], set()
    for source in sources:
        lines.append(f"// ---- src/{source.name} ----")
        lines += expand(source, seen)
        lines.append("")
    (out / "catenae.cpp").write_text("\n".join(lines))
    if (out / "include").exists():
        shutil.rmtree(out / "include")
    shutil.copytree(REPO / "include", out / "include")
    print(f"{out / 'catenae.cpp'}: {len(sources)} source(s); {out / 'include'}: the public headers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
