#!/usr/bin/env python3
# Copyright 2026 Timothy Place and the catenae contributors
"""The amalgamation (D26, PLAN.md section 7.4): catenae for any other build system.

    scripts/amalgamate.py --out DIR [--checks boundary|audit] [--fft-f32 own|none] ...

writes DIR/catenae.cpp, the whole compiled core as one source (every file of src/ in name
order, a private header of src/ inlined at its first include), DIR/include/, a copy of the
public headers, and DIR/include/catenae/config.h, the configuration a build system would
otherwise write: the check level, boundary unless --checks says audit, and each sample type's
FFT back end, own unless --fft-f32, --fft-f64, --fft-q15 or --fft-q31 says none. A consumer compiles
catenae.cpp with DIR/include on its include path and its own target flags, and links a handler
(src/handler/trap.cpp is the default, beside it as DIR/check_failed_trap.cpp).

An assumption of use, stated in the file: no compiler honours a contraction pragma reliably,
so the amalgamation cannot carry the library's contraction policy, and catenae.cpp must be
compiled with contraction off (-ffp-contract=off; MSVC's default /fp:precise).
"""
import argparse
import pathlib
import re
import shutil
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
# Each sample type's FFT back ends (PLAN.md section 7.2), as CMake and the wscript list them;
# CMSIS-DSP and vDSP arrive at C6.
FFT_CHOICES = {"f32": ["own", "cmsis", "vdsp", "none"], "f64": ["own", "vdsp", "none"],
               "q15": ["own", "cmsis", "none"], "q31": ["own", "cmsis", "none"]}
LATER = ("cmsis", "vdsp")
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"')
BANNER = """// catenae.cpp: catenae's compiled core in one file, generated by scripts/amalgamate.py.
// Copyright 2026 Timothy Place and the catenae contributors
//
// Compile it with the include/ directory beside it on the include path, with your target's
// flags, and with floating-point contraction off (-ffp-contract=off; MSVC's default
// /fp:precise): the library's bit pins assume it, and no pragma can carry it reliably
// (PLAN.md section 7.4). Under Clang or MSVC also raise the constant-evaluation limit, for the
// FFT's tables: -fconstexpr-steps=2000000000, /constexpr:steps2000000000 (AOU-012).
// Do not edit: regenerate it.
"""


def expand(path: pathlib.Path, seen: set[pathlib.Path]) -> list[str]:
    out = []
    for line in path.read_text().splitlines():
        m = INCLUDE.match(line)
        private = (REPO / "src" / m.group(1)).resolve() if m else None
        if private is not None and private.is_file():
            if private not in seen:
                seen.add(private)
                out.append(f"// ---- src/{m.group(1)} (inlined) ----")
                out += expand(private, seen)
            continue
        out.append(line)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", required=True, type=pathlib.Path)
    ap.add_argument("--checks", choices=["boundary", "audit"], default="boundary")
    for name, choices in FFT_CHOICES.items():
        ap.add_argument(f"--fft-{name}", choices=choices, default="own",
                        help=f"the {name} FFT back end (PLAN.md section 7.2) [default: own]")
    args = ap.parse_args()
    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    sources = sorted((REPO / "src").glob("*.cpp"))
    if not sources:
        raise SystemExit("no sources under src/")
    lines, seen = [BANNER], set()
    for source in sources:
        lines.append(f"// ---- src/{source.name} ----")
        lines += expand(source, seen)
        lines.append("")
    (out / "catenae.cpp").write_text("\n".join(lines))
    if (out / "include").exists():
        shutil.rmtree(out / "include")
    shutil.copytree(REPO / "include", out / "include")
    template = (REPO / "tools" / "config" / "config.h.in").read_text()
    config = template.replace("@CATENAE_CONFIG_WRITER@", "scripts/amalgamate.py")
    config = config.replace("@CATENAE_CHECKS_VALUE@", f"CATENAE_CHECKS_{args.checks.upper()}")
    for name in FFT_CHOICES:
        choice = getattr(args, f"fft_{name}")
        if choice in LATER:
            raise SystemExit(f"--fft-{name}={choice}: that back end arrives at C6 (PLAN.md section 10)")
        config = config.replace(f"@CATENAE_FFT_{name.upper()}_VALUE@", f"CATENAE_FFT_{choice.upper()}")
    (out / "include" / "catenae" / "config.h").write_text(config)
    shutil.copyfile(REPO / "src" / "handler" / "trap.cpp", out / "check_failed_trap.cpp")
    print(f"{out / 'catenae.cpp'}: {len(sources)} source(s); {out / 'include'}: the public headers and a "
          f"{args.checks} config.h; {out / 'check_failed_trap.cpp'}: the default handler")
    return 0


if __name__ == "__main__":
    sys.exit(main())
