/// @file fft_fir_tables.cpp
/// @brief The FFT FIR's table generator (PLAN.md 3.3, 12): writes a long low-pass's taps and the
/// spectrum its FFT FIR multiplies by as constants, so that an image whose designs are tables
/// runs no designer and links no software double.
// Copyright 2026 Timothy Place and the catenae contributors
//
//   catenae_tablegen_fft_fir EXAMPLE_HEADER
//
// writes examples/fft_fir_tables.h: the 255 float taps of fir_design<float, 255>::make() for a
// low-pass at 0.1 cycles per sample, 80 dB down, and the 257 bins of
// fft_fir_design<float, 255, 256>::make() of those taps, each part printed in hexadecimal so that
// every bit is written. Both are the library's own make(), linked from the core, so the tables
// are what the designers give on the build that runs this. CTest runs it on the hosted Linux legs
// and fails when the committed file is not what it writes (tablegen.FftFirTablesAreTheGeneratorsOutput);
// another libm may round the Kaiser design's sine otherwise.
#include <algorithm>
#include <array>
#include <cstddef>
#include <cstdio>
#include <string>
#include <vector>

#include "catenae/fft_fir_design.h"
#include "catenae/fir_design.h"

namespace {

    constexpr std::size_t k_taps  = 255;
    constexpr std::size_t k_block = 256;

    using taps_design     = catenae::fir_design<float, k_taps>;
    using spectrum_design = catenae::fft_fir_design<float, k_taps, k_block>;

    /// A float as a hexadecimal literal: every bit, and the suffix.
    std::string literal(float v) {
        char text[64];
        std::snprintf(text, sizeof text, "%af", static_cast<double>(v));
        return text;
    }

    /// One value a line, each with its index, the comments aligned as clang-format aligns them.
    std::string lines(const std::vector<std::string>& values, const char* name) {
        std::size_t widest = 0;
        for (const std::string& v : values) {
            widest = std::max(widest, v.size() + 1);
        }
        std::string s;
        char        line[160];
        for (std::size_t i = 0; i < values.size(); ++i) {
            const std::string v = values[i] + ",";
            std::snprintf(line, sizeof line, "        %-*s // %s[%zu]\n", static_cast<int>(widest), v.c_str(), name, i);
            s += line;
        }
        return s;
    }

    const char* const k_head = R"(/// @file fft_fir_tables.h
/// @brief A long low-pass as tables in ROM: 255 float taps at 0.1 of the sample rate, 80 dB down,
/// and the spectrum its FFT FIR multiplies by in blocks of 256. Generated by tools/tablegen, never
/// edited by hand (guide: Long filters).
// Copyright 2026 Timothy Place and the catenae contributors
//
// Generated by tools/tablegen/fft_fir_tables.cpp; regenerate with
//   catenae_tablegen_fft_fir examples/fft_fir_tables.h
//
// The generator runs the library's own make(): fir_design<float, 255>::make(fir_lowpass{0.1,
// 80.0}, ...) for the taps, then fft_fir_design<float, 255, 256>::make() of them for the spectrum,
// on the hosted Linux build (GCC 13, glibc's sin, sqrt and pow). Each part is in hexadecimal, so
// every bit is written. The battery checks the tables against make() on every leg (test_fft_fir.cpp,
// ATableDesignIsWhatMakeGives). Nothing here runs a designer: an image whose designs are all tables
// links no software double and no libm.
#ifndef CATENAE_EXAMPLES_FFT_FIR_TABLES_H
#define CATENAE_EXAMPLES_FFT_FIR_TABLES_H

#include <array>

#include "catenae/fft_fir_design.h"
#include "catenae/fir_design.h"
#include "catenae/sample_format.h"

namespace example {

    /// The low-pass's taps in float: 255, symmetric, a delay of exactly 127 frames.
    inline constexpr std::array<float, 255> long_lowpass_taps = {{
)";

    const char* const k_middle = R"(    }};
    // ANCHOR: direct
    /// The direct form's design: a view of the taps.
    inline constexpr auto long_lowpass = catenae::fir_design<float, 255>::from_table(long_lowpass_taps);
    // ANCHOR_END: direct

    /// The taps' spectrum over a transform of 512, times 2/512: 257 bins, DC to Nyquist.
    inline constexpr std::array<catenae::complex<float>, 257> long_lowpass_spectrum = {{
)";

    const char* const k_tail = R"(    }};
    // ANCHOR: spectrum
    /// The FFT FIR's design, in blocks of 256: a view of the spectrum, checked as it compiles.
    inline constexpr auto long_lowpass_fft =
        catenae::fft_fir_design<float, 255, 256>::from_table(long_lowpass_spectrum);
    // ANCHOR_END: spectrum

} // namespace example

#endif // CATENAE_EXAMPLES_FFT_FIR_TABLES_H
)";

} // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        std::fprintf(stderr, "usage: catenae_tablegen_fft_fir EXAMPLE_HEADER\n");
        return 2;
    }
    static std::array<float, k_taps>                                             taps{};
    static std::array<double, taps_design::workspace_size>                       taps_work{};
    static spectrum_design::table_type                                           spectrum{};
    static std::array<catenae::complex<double>, spectrum_design::workspace_size> spectrum_work{};
    const auto made = taps_design::make(catenae::fir_lowpass{0.1, 80.0}, catenae::span<float, k_taps>(taps),
                                        catenae::span<double, taps_design::workspace_size>(taps_work));
    if (!made) {
        std::fprintf(stderr, "catenae_tablegen_fft_fir: the low-pass was refused\n");
        return 1;
    }
    const auto bins =
        spectrum_design::make(*made, catenae::span<spectrum_design::bin_type, spectrum_design::bins>(spectrum),
                              catenae::span<catenae::complex<double>, spectrum_design::workspace_size>(spectrum_work));
    if (!bins) {
        std::fprintf(stderr, "catenae_tablegen_fft_fir: the spectrum was refused\n");
        return 1;
    }
    std::vector<std::string> h;
    for (const float v : taps) {
        h.push_back(literal(v));
    }
    std::vector<std::string> spec;
    for (const catenae::complex<float>& v : spectrum) {
        spec.push_back("{" + literal(v.re) + ", " + literal(v.im) + "}");
    }
    const std::string text = std::string(k_head) + lines(h, "h") + k_middle + lines(spec, "H") + k_tail;
    std::FILE* const  f    = std::fopen(argv[1], "wb");
    if (f == nullptr) {
        std::fprintf(stderr, "catenae_tablegen_fft_fir: cannot write %s\n", argv[1]);
        return 1;
    }
    const bool ok = std::fwrite(text.data(), 1, text.size(), f) == text.size();
    return std::fclose(f) == 0 && ok ? 0 : 1;
}
